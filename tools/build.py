DAYS = ["月曜日", "火曜日", "水曜日", "木曜日", "金曜日", "土曜日", "日曜日"]
SHORT = {"月曜日": "月", "火曜日": "火", "水曜日": "水", "木曜日": "木",
         "金曜日": "金", "土曜日": "土", "日曜日": "日"}


def summarize_hours(blocks):
    """曜日ごとの行を『毎日 10:00〜22:00』のように畳む"""
    if not blocks:
        return "", []
    label, lines = blocks[0]
    per = {}
    extra = []
    for l in lines:
        m = re.match(r'^(月|火|水|木|金|土|日)曜日[:：]?\s*(.+)$', l)
        if m:
            per[m.group(1) + "曜日"] = m.group(2).strip()
        else:
            extra.append(l)
    if not per:
        return "", lines
    groups = []
    for d in DAYS:
        v = per.get(d)
        if v is None:
            continue
        if groups and groups[-1][1] == v:
            groups[-1][0].append(d)
        else:
            groups.append([[d], v])
    if len(groups) == 1 and len(groups[0][0]) == 7:
        return groups[0][1], extra
    parts = []
    for ds, v in groups:
        if "定休" in v:
            continue
        tag = SHORT[ds[0]] if len(ds) == 1 else SHORT[ds[0]] + "〜" + SHORT[ds[-1]]
        parts.append(tag + " " + v)
    return " ／ ".join(parts), extra


